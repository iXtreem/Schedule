
// ============================================================
// bellUtils.js — утилиты работы со строками «Время пар».
//
// Формат строки слота (как в backend TB_BellSchedule.TimeText):
//   "8:00-8:45<br>8:50-9:30" — пара с переменой внутри;
//   "8:00-9:00"              — старый формат выходных дней БЕЗ перемены.
//
// Задача модуля — привести любые строки к единому виду:
// выходные дни отображаются так же, как рабочие (с указанием перемены),
// а не одним часовым блоком «8:00-9:00».
// ============================================================

// Регулярка одного временного диапазона "H:MM-H:MM" (часы 0-23).
const RANGE_RE = /(\d{1,2}):(\d{2})\s*-\s*(\d{1,2}):(\d{2})/g;

/**
 * Разбивает строку времени на части: ["8:00-8:45", "8:50-9:30"].
 * В качестве разделителя выступают <br> либо перевод строки.
 */
export function splitBellParts(text) {
  return String(text || "")
    .split(/<br\s*\/?>|\n/i)
    .map((s) => s.trim())
    .filter(Boolean);
}

/**
 * Ищет все диапазоны "HH:MM-HH:MM" во всех частях строки.
 * Возвращает массив вида [{h1,m1,h2,m2}, ...] — по одному на каждую часть.
 */
function findRanges(parts) {
  return parts.map((p) => {
    const m = RANGE_RE.exec(p);
    RANGE_RE.lastIndex = 0; // регулярка с флагом g хранит позицию — сбрасываем
    return m
      ? { h1: +m[1], m1: +m[2], h2: +m[3], m2: +m[4] }
      : null;
  });
}

// Стандартный перерыв внутри пары (мин) — то же значение по умолчанию,
// что использует вкладка «Время пар» (lessonTimes.js: DEFAULT_INNER_BREAK).
// Используется в словаре PAIR_REF ниже при сверке эталонных перемен.

// Эталонные пары «первый блок -> второй блок», снятые с настроек по умолчанию
// (backend/lib/bell.php, BELL_DEFAULTS). Служат словарём: если в БД/источнике
// до фронтена дошёл только ПЕРВЫЙ блок пары (например «8:00-8:45» вместо
// «8:00-8:45<br>8:50-9:30»), по началу строки находим эталон и достраиваем
// недостающие блоки ТОЧНО (с реальными переменами 5/10 мин), а не «на глазок».
// 5-7 пары рабочих дней сознательно не включены: их вторые блоки короче 45 мин
// (17:20 вместо 17:25), и достроить их из одной строки однозначно нельзя —
// для них действует общее правило (ниже).
const PAIR_REF = new Map([
  ["8:00-8:45",   "8:50-9:30"],    // рабочие + воскресные, 1-я пара
  ["10:00-10:45", "10:50-11:30"],  // рабочие, 2-я пара
  ["12:00-12:45", "12:50-13:30"],  // рабочие, 3-я пара
  ["14:00-14:45", "14:50-15:30"],  // рабочие, 4-я пара
  ["9:40-10:25",  "10:30-11:10"],  // воскресная, 2-я пара
  ["11:20-12:05", "12:10-12:50"],  // воскресная, 3-я пара
  ["13:00-13:45", "13:50-14:30"],  // воскресная, 4-я пара
  ["14:40-15:25", "15:30-16:15"],  // воскресная, 5-я пара
  ["16:25-17:10", "17:15-18:00"],  // воскресная, 6-я пара
  ["18:10-18:55", "19:00-19:45"],  // воскресная, 7-я пара
]);

/**
 * Приводит строку времени пары к виду с переменой: ДВА блока, разделённых <br>.
 *
 * История бага:
 *  1. «8:00-8:22 / 8:22-8:45»: старая версия функции любую одиночную строку
 *     резала строго пополам — корректный слот, дошедший до фронта без <br>
 *     (старая запись в БД, другой клиент, ручная правка), превращался в абсурд.
 *  2. «Отображается просто 8:00-8:45»: после первого исправления одиночный
 *     45-минутный блок стали оставлять как есть — но в источнике у рабочих
 *     дней хранилась ровно такая строка (без второго блока), и нужный вид
 *     «8:00-8:45 / 8:50-9:30» нигде не появлялся.
 *
 * Нынешние правила:
 *  - Несколько частей ("8:00-8:45<br>8:50-9:30") — строка корректна,
 *    возвращаем как есть.
 *  - Одиночная строка совпадает с первым блоком эталонной пары (словарь
 *    PAIR_REF) — достраиваем второй блок точно из эталона:
 *    "8:00-8:45" -> "8:00-8:45<br>8:50-9:30".
 *  - Прочие одиночные диапазоны ("8:00-9:00", "8:00-9:30", нестандартные
 *    45-минутные блоки) — делим пополам, конец второго блока всегда совпадает
 *    с концом исходной строки: "8:00-9:00" -> "8:00-8:30<br>8:30-9:00".
 *  - Пустые/нестандартные строки ("—", "окно") оставляем без изменений.
 */
export function normalizeBellText(text) {
  const raw = String(text || "").trim();
  if (!raw) return raw;

  const parts = splitBellParts(raw);
  if (parts.length !== 1) return raw; // уже разбита на 2+ блока — ок

  const [r] = findRanges(parts);
  if (!r) return raw; // не диапазон — не трогаем

  const start = r.h1 * 60 + r.m1;
  const end = r.h2 * 60 + r.m2;
  if (!(end > start)) return raw; // бессмысленный интервал — не трогаем

  // Формат «как в рабочих днях»: часы без ведущего нуля, минуты с ведущим нулём.
  const fmt = (min) => `${Math.floor(min / 60)}:${String(min % 60).padStart(2, "0")}`;

  // Точное восстановление по эталону: строка = первый блок известной пары.
  const ref = PAIR_REF.get(`${fmt(start)}-${fmt(end)}`);
  if (ref) return `${fmt(start)}-${fmt(end)}<br>${ref}`;

  // Общее правило: делим пополам. Конец второго блока ВСЕГДА совпадает с
  // концом исходной строки, поэтому абсурдных разрезов вида
  // «8:00-8:22 / 8:22-8:45» больше не будет.
  const mid = Math.floor((start + end) / 2);
  return `${fmt(start)}-${fmt(mid)}<br>${fmt(mid)}-${fmt(end)}`;
}

/**
 * Проверяет, что строка времени содержит перемену (разбита на 2 блока).
 * Используется для диагностики/тестов.
 */
export function hasBreakInside(text) {
  return splitBellParts(text).length >= 2;
}